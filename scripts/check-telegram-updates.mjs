import fs from 'node:fs/promises';
import path from 'node:path';

const CHANGELOG_URL = 'https://core.telegram.org/bots/api-changelog';
const STATE_FILE = path.resolve('./telegram_api_state.json');

// Biến môi trường
const TELEGRAM_BOT_TOKEN = process.env.TELEGRAM_BOT_TOKEN || '';
const TELEGRAM_CHAT_ID = process.env.TELEGRAM_CHAT_ID || '';
const GITHUB_TOKEN = process.env.GITHUB_TOKEN || process.env.GH_TOKEN || '';
const GITHUB_REPOSITORY = process.env.GITHUB_REPOSITORY || 'Nam088/telebot-ts';

/**
 * 1. Fetch & Parse phiên bản cập nhật mới nhất từ Telegram Bot API Changelog
 */
async function fetchLatestApiUpdate() {
  const response = await fetch(CHANGELOG_URL, {
    headers: {
      'User-Agent': 'Mozilla/5.0 (Telegram-Bot-API-Watcher/1.0)',
    },
  });

  if (!response.ok) {
    throw new Error(`HTTP error! Status: ${response.status}`);
  }

  const html = await response.text();

  // Bóc tách ngày và version mới nhất
  const dateMatch = html.match(/<h4>(?:<a[^>]*>.*?<\/a>)?(.*?)<\/h4>/i);
  const versionMatch = html.match(/<p><strong>(Bot API\s*[\d.]+)<\/strong><\/p>/i);

  const date = dateMatch && dateMatch[1] ? dateMatch[1].replace(/<[^>]+>/g, '').trim() : 'Unknown Date';
  const version = versionMatch && versionMatch[1] ? versionMatch[1].trim() : 'Unknown Version';

  // Lấy toàn bộ đoạn tóm tắt của version đầu tiên
  const firstSection = html.split(/<h4>/i)[1] || '';

  // Trích xuất các danh mục thay đổi
  const features = [];
  const sectionParts = firstSection.split(/<p><strong>/gi).slice(1);

  for (const part of sectionParts) {
    const categoryTitle = part.split('</strong>')[0]?.trim();
    if (categoryTitle && !categoryTitle.toLowerCase().includes('bot api')) {
      const items = [...part.matchAll(/<li>(.*?)<\/li>/gi)].map(m =>
        m[1]
          .replace(/<[^>]+>/g, '')
          .replace(/&amp;/g, '&')
          .replace(/&lt;/g, '<')
          .replace(/&gt;/g, '>')
          .replace(/&#39;/g, "'")
          .replace(/&quot;/g, '"')
          .trim()
      );
      if (items.length > 0) {
        features.push({ category: categoryTitle, items });
      }
    }
  }

  return {
    version,
    date,
    features,
    url: CHANGELOG_URL,
  };
}

/**
 * 2. Kiểm tra xem GitHub Issue cho version này đã tồn tại chưa (tránh tạo trùng lặp)
 */
async function checkExistingGithubIssue(version) {
  if (!GITHUB_TOKEN) return false;

  try {
    const res = await fetch(`https://api.github.com/repos/${GITHUB_REPOSITORY}/issues?state=all&per_page=30`, {
      headers: {
        Authorization: `Bearer ${GITHUB_TOKEN}`,
        Accept: 'application/vnd.github.v3+json',
        'User-Agent': 'Telegram-API-Watcher',
      },
    });

    if (!res.ok) return false;

    const issues = await res.json();
    return issues.some(issue => issue.title && issue.title.includes(version));
  } catch (err) {
    console.warn('⚠️ Không thể kiểm tra danh sách issues trên GitHub:', err.message);
    return false;
  }
}

/**
 * 3. Tự động tạo GitHub Issue với checklist Markdown
 */
async function createGithubIssue(updateInfo) {
  const issueTitle = `feat(api): Telegram ${updateInfo.version} support (${updateInfo.date})`;
  
  let issueBody = `## 🚀 Telegram ${updateInfo.version} Released\n\n`;
  issueBody += `**Release Date:** ${updateInfo.date}\n`;
  issueBody += `**Changelog Source:** [core.telegram.org/bots/api-changelog](${updateInfo.url})\n\n`;
  issueBody += `### 📋 Action Items / Checklist\n\n`;

  for (const feat of updateInfo.features) {
    issueBody += `#### ${feat.category}\n`;
    for (const item of feat.items) {
      issueBody += `- [ ] ${item}\n`;
    }
    issueBody += `\n`;
  }

  issueBody += `---\n*Automated notification generated by \`check-telegram-updates.mjs\`* 🤖`;

  if (!GITHUB_TOKEN) {
    console.log('\n[INFO] Chưa có GITHUB_TOKEN. Nội dung Issue sẽ tạo như sau:');
    console.log('==================================================');
    console.log(`Title: ${issueTitle}\n`);
    console.log(issueBody);
    console.log('==================================================');
    return;
  }

  // Kiểm tra xem issue cho version này đã được tạo trước đó chưa
  const exists = await checkExistingGithubIssue(updateInfo.version);
  if (exists) {
    console.log(`ℹ️ Issue cho ${updateInfo.version} đã tồn tại trên GitHub. Bỏ qua tạo mới.`);
    return;
  }

  const res = await fetch(`https://api.github.com/repos/${GITHUB_REPOSITORY}/issues`, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${GITHUB_TOKEN}`,
      Accept: 'application/vnd.github.v3+json',
      'Content-Type': 'application/json',
      'User-Agent': 'Telegram-API-Watcher',
    },
    body: JSON.stringify({
      title: issueTitle,
      body: issueBody,
      labels: ['enhancement', 'telegram-api-update'],
    }),
  });

  const data = await res.json();
  if (res.ok) {
    console.log(`🎉 Đã tạo thành công GitHub Issue: ${data.html_url}`);
  } else {
    console.error('❌ Tạo GitHub Issue thất bại:', data);
  }
}

/**
 * 4. Gửi thông báo Telegram (tuỳ chọn)
 */
async function sendTelegramAlert(updateInfo) {
  if (!TELEGRAM_BOT_TOKEN || !TELEGRAM_CHAT_ID) return;

  let text = `🚀 *Telegram Bot API Cập Nhật Mới!*\n\n`;
  text += `📌 *Phiên bản:* ${updateInfo.version}\n`;
  text += `📅 *Ngày phát hành:* ${updateInfo.date}\n\n`;
  text += `*Các điểm mới nổi bật:*\n`;

  for (const feat of updateInfo.features.slice(0, 4)) {
    text += `\n🔹 *${feat.category}:*\n`;
    for (const item of feat.items.slice(0, 3)) {
      text += `  • ${item.length > 120 ? item.slice(0, 117) + '...' : item}\n`;
    }
  }

  text += `\n🔗 [Xem chi tiết tại Telegram Changelog](${updateInfo.url})`;

  try {
    await fetch(`https://api.telegram.org/bot${TELEGRAM_BOT_TOKEN}/sendMessage`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        chat_id: TELEGRAM_CHAT_ID,
        text: text,
        parse_mode: 'Markdown',
        disable_web_page_preview: false,
      }),
    });
    console.log('✅ Đã gửi thông báo đến Telegram!');
  } catch (err) {
    console.error('❌ Gửi tin nhắn Telegram thất bại:', err.message);
  }
}

/**
 * 5. Main entrypoint
 */
async function main() {
  console.log('🔍 Đang kiểm tra Telegram Bot API Changelog...');
  const latest = await fetchLatestApiUpdate();

  let lastState = null;
  try {
    const raw = await fs.readFile(STATE_FILE, 'utf-8');
    lastState = JSON.parse(raw);
  } catch {
    console.log('ℹ️ Chưa có file state lưu trữ cũ.');
  }

  const isNew = !lastState || lastState.version !== latest.version || lastState.date !== latest.date;

  if (isNew) {
    console.log(`\n🎉 PHÁT HIỆN CẬP NHẬT MỚI! (${lastState?.version || 'Chưa lưu'} -> ${latest.version})`);
    
    // 1. Tạo GitHub Issue với checklist
    await createGithubIssue(latest);

    // 2. Gửi Telegram Alert (nếu có cấu hình)
    await sendTelegramAlert(latest);

    // 3. Cập nhật state file
    await fs.writeFile(STATE_FILE, JSON.stringify(latest, null, 2), 'utf-8');
    console.log(`💾 Đã lưu trạng thái mới vào ${STATE_FILE}`);
  } else {
    console.log(`✅ Hiện tại không có cập nhật mới. Đang ở bản mới nhất: ${latest.version} (${latest.date})`);
  }
}

main().catch(console.error);
